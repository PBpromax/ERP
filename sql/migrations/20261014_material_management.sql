    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp, updated_at timestamp, created_by varchar(255), updated_by varchar(255),
    deleted boolean DEFAULT false,
    material_id bigint NOT NULL REFERENCES material(id), business_date date NOT NULL,
    purchase_qty numeric(18,3) NOT NULL CHECK (purchase_qty >= 0),
    production_qty numeric(18,3) NOT NULL CHECK (production_qty >= 0),
    loss_qty numeric(18,3) NOT NULL CHECK (loss_qty >= 0),
    remark varchar(1000), version_no bigint DEFAULT 0,
    CONSTRAINT uq_material_daily_date UNIQUE (material_id, business_date)
