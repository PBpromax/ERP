-- Apply to the local preview database only for this change.
BEGIN;
CREATE TABLE IF NOT EXISTS sales_return (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp, updated_at timestamp, created_by varchar(255), updated_by varchar(255),
    deleted boolean DEFAULT false,
    order_id bigint, order_item_id bigint, customer_id bigint,
    customer_name varchar(200), order_no varchar(64), product_code varchar(64),
    product_name varchar(200), spec varchar(200), unit varchar(30), return_date date,
    qty numeric(18,3), unit_price numeric(18,5), amount numeric(18,2), remark varchar(500)
);
CREATE INDEX IF NOT EXISTS idx_sales_return_order_item ON sales_return(order_item_id);
ALTER TABLE statement_item ADD COLUMN IF NOT EXISTS return_id bigint;
ALTER TABLE statement_item ALTER COLUMN unit_price TYPE numeric(18,5);
CREATE INDEX IF NOT EXISTS idx_statement_item_return ON statement_item(return_id);
COMMIT;
